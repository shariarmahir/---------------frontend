const byHandle = new Map(people.map((p) => [p.handle, p]));

export function getPerson(handle: string): Person | undefined {
  return byHandle.get(handle);
}

/** For data that must reference a real person; throws on a typo. */
export function personOrThrow(handle: string): Person {
  const p = byHandle.get(handle);
  if (!p) throw new Error(`Unknown person: ${handle}`);
  return p;
}

export const currentUser: Person = personOrThrow(CURRENT_USER_HANDLE);

/**
 * A person's headline trust number for listings: the named skill as the
 * community rates it (or their most-rated skill when none is named). A
 * skill nobody has rated yet shows as unrated — never borrows another
 * skill's rating.
 */
export function verifiedRatingFor(p: Person, skill?: string): SkillRating {
  if (!skill) return [...p.skills].sort((a, b) => b.raters - a.raters)[0];
  return p.skills.find((x) => x.skill === skill) ?? { skill, category: p.categories[0], self: 0, communityAvg: 0, raters: 0 };
}
